export type AgentMessages = { readonly [Key in keyof (typeof translations)["en"]]: string };

export function resolveBrowserLocale(): AgentLocale {
  if (typeof navigator === "undefined") return "en";
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function messagesFor(locale: AgentLocale): AgentMessages {
  return translations[locale];
}
